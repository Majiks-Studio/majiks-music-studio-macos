//! The provenance manifest builder: the headline differentiator.
//!
//! The command journal IS the chain of custody (02-ARCHITECTURE section 4): the
//! per-clip lineage tree and the AI-disclosure manifest are VIEWS over it plus
//! asset content hashes. This module builds the machine-readable manifest from
//! `(project, journal, hash-chain head)`:
//!   - every current clip classified generated / imported / recorded,
//!   - the generated/imported/recorded split by clip audio duration and by count,
//!   - per-clip lineage (prompt, model, seed, steps, device, sourceCommand),
//!   - the blake3 hash-chain head (tip + entry count + genesis),
//!   - the EU AI Act Article 50(2) machine-readable disclosure fields, with the
//!     IPTC `digitalSourceType` controlled-vocabulary term on generated content.
//!
//! It is honest by construction: a clip is "generated" only when its content
//! hash is carried by a `gen.landed` record (or a take), and a song a person
//! declared as imported stays imported even after separation. Nothing here
//! invents provenance; a clip with no generative record reads as imported.
//!
//! Contract: `engine/contracts/provenance-manifest.schema.json` (proposed
//! additive schema; the manifest validates against it).

use std::collections::{BTreeMap, HashMap, HashSet};

use serde_json::{json, Map, Value};

use timeline_core::model::{Clip, Project};
use timeline_core::{Envelope, GENESIS_HASH};

pub const MANIFEST_VERSION: u64 = 1;

// IPTC DigitalSourceType controlled-vocabulary IRIs (cv.iptc.org). These are the
// machine-readable AI-disclosure values C2PA and the EU AI Act ecosystem key on.
const IPTC_TRAINED: &str = "http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia";
const IPTC_COMPOSITE: &str =
    "http://cv.iptc.org/newscodes/digitalsourcetype/compositeWithTrainedAlgorithmicMedia";
const IPTC_CAPTURE: &str = "http://cv.iptc.org/newscodes/digitalsourcetype/digitalCapture";
// "Media created by a human using non-generative tools" — the IPTC term for a
// note clip written in the piano roll. Verified against cv.iptc.org (it
// supersedes the retired `digitalArt`, Sept 2024). A piano-roll clip was not
// captured by any device, so `digitalCapture` is as false for it as "imported".
const IPTC_CREATION: &str = "http://cv.iptc.org/newscodes/digitalsourcetype/digitalCreation";

/// How a clip's current content came to be.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ClipOrigin {
    /// AI-generated by a music model (a `gen.landed` record carries its hash).
    Generated,
    /// Imported audio (or an imported song separated into stems).
    Imported,
    /// Captured from an input: audio through `record.stop` (a `gen.landed` with
    /// `sourceCommand: record.commit`), or a MIDI take played on a controller.
    Recorded,
    /// Notes written here, in the piano roll. No asset, no capture, no model.
    Authored,
}

impl ClipOrigin {
    fn wire(self) -> &'static str {
        match self {
            ClipOrigin::Generated => "generated",
            ClipOrigin::Imported => "imported",
            ClipOrigin::Recorded => "recorded",
            ClipOrigin::Authored => "authored",
        }
    }

    fn digital_source_type(self) -> &'static str {
        match self {
            ClipOrigin::Generated => IPTC_TRAINED,
            ClipOrigin::Imported | ClipOrigin::Recorded => IPTC_CAPTURE,
            ClipOrigin::Authored => IPTC_CREATION,
        }
    }

    /// The manifest wire term, for callers outside this module (the snapshot's
    /// per-clip `origin` field, which must never drift from the manifest's).
    pub fn as_str(self) -> &'static str {
        self.wire()
    }
}

/// The generative provenance found for a clip (from a take or a `gen.landed`).
struct GenRecord {
    source_command: String,
    request_id: String,
    take_id: Option<String>,
    engine_identity: Value,
}

/// A compact provenance summary, reused by the export result JSON and the schema
/// (the manifest embeds it under `composition`).
#[derive(Debug, Clone, Default)]
pub struct Composition {
    pub clip_count: usize,
    pub generated_clips: usize,
    pub imported_clips: usize,
    pub recorded_clips: usize,
    pub authored_clips: usize,
    pub total_ticks: u64,
    pub generated_ticks: u64,
    pub imported_ticks: u64,
    pub recorded_ticks: u64,
    pub authored_ticks: u64,
}

impl Composition {
    /// Fold one classified clip in. The single place a clip is counted, so the
    /// manifest, the export summary and the snapshot can never split by origin
    /// differently from one another.
    fn add(&mut self, origin: ClipOrigin, length_ticks: u64) {
        self.clip_count += 1;
        self.total_ticks = self.total_ticks.saturating_add(length_ticks);
        let (clips, ticks) = match origin {
            ClipOrigin::Generated => (&mut self.generated_clips, &mut self.generated_ticks),
            ClipOrigin::Imported => (&mut self.imported_clips, &mut self.imported_ticks),
            ClipOrigin::Recorded => (&mut self.recorded_clips, &mut self.recorded_ticks),
            ClipOrigin::Authored => (&mut self.authored_clips, &mut self.authored_ticks),
        };
        *clips += 1;
        *ticks = ticks.saturating_add(length_ticks);
    }
}

impl Composition {
    pub fn generated_fraction(&self) -> f64 {
        if self.total_ticks == 0 {
            0.0
        } else {
            self.generated_ticks as f64 / self.total_ticks as f64
        }
    }

    fn pct(part: u64, total: u64) -> f64 {
        if total == 0 {
            0.0
        } else {
            // One decimal place, deterministic (byte-stable manifests).
            (part as f64 * 1000.0 / total as f64).round() / 10.0
        }
    }

    pub fn to_json(&self) -> Value {
        json!({
            "clipCount": self.clip_count,
            "byClipCount": {
                "generated": self.generated_clips,
                "imported": self.imported_clips,
                "recorded": self.recorded_clips,
                "authored": self.authored_clips,
            },
            "byDuration": {
                "totalTicks": self.total_ticks,
                "generatedTicks": self.generated_ticks,
                "importedTicks": self.imported_ticks,
                "recordedTicks": self.recorded_ticks,
                "authoredTicks": self.authored_ticks,
                "generatedPct": Self::pct(self.generated_ticks, self.total_ticks),
                "importedPct": Self::pct(self.imported_ticks, self.total_ticks),
                "recordedPct": Self::pct(self.recorded_ticks, self.total_ticks),
                "authoredPct": Self::pct(self.authored_ticks, self.total_ticks),
            },
            "durationBasis": "sum of clip audio durations across all tracks (each clip counted once; overlaps not deduplicated)",
        })
    }

    /// A one-line human summary, e.g. "62% generated / 38% imported" (the empty-
    /// project inspector line, 01-DESIGN 3.5).
    pub fn summary_line(&self) -> String {
        if self.clip_count == 0 {
            return "empty project".to_string();
        }
        let mut parts = Vec::new();
        for (ticks, label) in [
            (self.generated_ticks, "generated"),
            (self.imported_ticks, "imported"),
            (self.recorded_ticks, "recorded"),
            (self.authored_ticks, "authored"),
        ] {
            if ticks > 0 {
                let pct = Self::pct(ticks, self.total_ticks);
                parts.push(format!("{pct:.0}% {label}"));
            }
        }
        if parts.is_empty() {
            format!("{} clips", self.clip_count)
        } else {
            parts.join(" / ")
        }
    }
}

/// Build the full provenance manifest as JSON. `entry_count` and `tip_hash` are
/// the hash-chain head (`session.seq()` / `session.tip_hash()`).
pub fn build_manifest(
    project: &Project,
    journal: &[Envelope],
    tip_hash: &str,
    entry_count: u64,
) -> Value {
    let rate = project.sample_rate;
    let ticks_to_seconds = |ticks: u64| -> f64 {
        project.tempo.tick_to_frame(ticks, rate) as f64 / f64::from(rate.max(1))
    };

    let mut comp = Composition::default();
    let mut clips_json: Vec<Value> = Vec::new();
    let mut models: BTreeMap<String, ()> = BTreeMap::new();
    let index = OriginIndex::build(project, journal);

    for track in &project.tracks {
        for clip in &track.clips {
            let (origin, lineage) = classify_clip(clip, &index);
            comp.add(origin, clip.length_ticks);
            if origin == ClipOrigin::Generated {
                if let Some(m) = lineage
                    .get("engine")
                    .and_then(|e| e.get("model"))
                    .and_then(Value::as_str)
                {
                    models.insert(m.to_string(), ());
                }
            }

            let mut c = Map::new();
            c.insert("clipId".into(), json!(clip.id));
            c.insert("trackId".into(), json!(track.id));
            c.insert("trackName".into(), json!(track.name));
            // HONEST OMISSION, not an empty value. A note clip has no asset
            // (`Clip::new_midi` leaves `source_id` empty), and `"assetHash": ""`
            // is a claim that the hash IS the empty string. The field is absent
            // when there is nothing to name — the same rule this module already
            // applies to `prompt`, `takeId` and every `engine` sub-field.
            if !clip.source_id.is_empty() {
                c.insert("assetHash".into(), json!(clip.source_id));
            }
            c.insert("startTicks".into(), json!(clip.start_ticks));
            c.insert("lengthTicks".into(), json!(clip.length_ticks));
            c.insert(
                "durationSeconds".into(),
                json!(round2(ticks_to_seconds(clip.length_ticks))),
            );
            c.insert("origin".into(), json!(origin.wire()));
            c.insert("digitalSourceType".into(), json!(origin.digital_source_type()));
            c.insert("lineage".into(), lineage);
            clips_json.push(Value::Object(c));
        }
    }

    let ai_generated = comp.generated_ticks > 0;
    let all_generated = ai_generated && comp.imported_ticks == 0 && comp.recorded_ticks == 0;
    let overall_dst = if !ai_generated {
        IPTC_CAPTURE
    } else if all_generated {
        IPTC_TRAINED
    } else {
        IPTC_COMPOSITE
    };
    let generated_pct = (comp.generated_fraction() * 100.0).round() as i64;
    let statement = if !ai_generated {
        "This audio contains no AI-generated material recorded in the session provenance.".to_string()
    } else {
        format!(
            // "imported or recorded" alone would leave out authored note clips
            // and silently under-describe the human half of a mixed project —
            // the same omission, in prose, that the origin enum used to make.
            "This audio contains AI-generated material. Approximately {generated_pct}% of its content duration was generated by an AI music model; the remainder is imported, recorded, or authored in the app. Per-clip generation details are listed under \"clips\".",
        )
    };
    let models_list: Vec<Value> = models.keys().map(|m| json!(m)).collect();

    let generated_at = journal
        .iter()
        .map(|e| e.ts.as_str())
        .max()
        .unwrap_or("")
        .to_string();

    let mut root = Map::new();
    root.insert("manifestVersion".into(), json!(MANIFEST_VERSION));
    root.insert("kind".into(), json!("majiks.provenance-manifest"));
    root.insert("generatedAt".into(), json!(generated_at));
    root.insert(
        "generator".into(),
        json!({ "app": "Majik's Music Studio", "component": "majiks-studio-daw/export" }),
    );
    root.insert(
        "project".into(),
        json!({
            "projectId": project.project_id,
            "name": project.name,
            "sampleRateHz": project.sample_rate,
            "tempoBpm": project.bpm_wire.as_f64(),
            "key": project.key,
            "durationTicks": project_end_ticks(project),
            "durationSeconds": round2(ticks_to_seconds(project_end_ticks(project))),
        }),
    );
    root.insert(
        "hashChain".into(),
        json!({
            "algorithm": "blake3",
            "genesisHash": GENESIS_HASH,
            "tipHash": tip_hash,
            "entryCount": entry_count,
        }),
    );
    root.insert("composition".into(), comp.to_json());
    root.insert(
        "aiDisclosure".into(),
        json!({
            "standard": "EU AI Act Article 50(2)",
            "vocabulary": "IPTC DigitalSourceType",
            "aiGenerated": ai_generated,
            "generatedFraction": round4(comp.generated_fraction()),
            "digitalSourceType": overall_dst,
            "statement": statement,
            "models": models_list,
        }),
    );
    root.insert("clips".into(), Value::Array(clips_json));
    Value::Object(root)
}

/// The composition split alone (backs the export result summary + the empty-
/// project inspector line, without building the whole manifest).
pub fn composition(project: &Project, journal: &[Envelope]) -> Composition {
    let index = OriginIndex::build(project, journal);
    let mut comp = Composition::default();
    for track in &project.tracks {
        for clip in &track.clips {
            let (origin, _) = classify_clip(clip, &index);
            comp.add(origin, clip.length_ticks);
        }
    }
    comp
}

/// Every clip's origin, keyed by clip id — the ONE classification the manifest,
/// the export summary and the snapshot all read, so a pre-export preview cannot
/// disagree with the artifact it previews.
pub fn clip_origins(project: &Project, journal: &[Envelope]) -> HashMap<String, ClipOrigin> {
    let index = OriginIndex::build(project, journal);
    project
        .tracks
        .iter()
        .flat_map(|t| t.clips.iter())
        .map(|c| (c.id.clone(), classify_clip(c, &index).0))
        .collect()
}

/// Who wrote a note clip's notes. Both flags can be true (a take overdubbed
/// into a clip that was already being written by hand).
#[derive(Debug, Default, Clone, Copy)]
struct NoteWriters {
    /// A `clip.placeMidi` / `note.add` stamped by the MIDI-capture actor.
    recorded: bool,
    /// The same commands from anywhere else: the piano roll, the Instrument
    /// button, an agent over MCP.
    authored: bool,
}

/// Every journal fact classification needs, collected in ONE pass.
///
/// Before this existed each clip re-scanned the whole journal three times, so
/// export was O(clips x journal). The snapshot now classifies too (the UI must
/// read the same answer as the manifest), and that is a 30 Hz path — it has to
/// be one pass, not one pass per clip.
struct OriginIndex<'a> {
    /// asset hash -> the generative record that produced it. Takes win over
    /// `gen.landed`, and the FIRST match wins, exactly as the per-clip search
    /// this replaced did.
    gen_by_hash: HashMap<&'a str, GenRecord>,
    /// requestId -> the originating `gen.*` request (never `gen.landed`).
    gen_request: HashMap<&'a str, &'a Envelope>,
    /// Clips placed by the host's import path (`clip.place`, actor `import`).
    imported: HashSet<&'a str>,
    /// Clips placed by a journaled `record.*` command. Empty in practice: every
    /// `record.*` in the catalog is `journaled: false`, so nothing can land
    /// here. Kept because the branch is free and stays correct if that changes.
    recorded_place: HashSet<&'a str>,
    /// Note clip -> who wrote its notes.
    note_writers: HashMap<&'a str, NoteWriters>,
    /// newClipId -> the clip it was split or duplicated from, so a derived note
    /// clip inherits the origin of the material it is made of.
    derived_from: HashMap<&'a str, &'a str>,
}

/// The actor name the MIDI/audio capture paths stamp their commands with
/// (`host.rs`: every `submit_json` in the record path uses `Actor::user("record")`).
/// Nothing else in the tree submits under this name.
const RECORD_ACTOR: &str = "record";

impl<'a> OriginIndex<'a> {
    fn build(project: &'a Project, journal: &'a [Envelope]) -> Self {
        let mut idx = OriginIndex {
            gen_by_hash: HashMap::new(),
            gen_request: HashMap::new(),
            imported: HashSet::new(),
            recorded_place: HashSet::new(),
            note_writers: HashMap::new(),
            derived_from: HashMap::new(),
        };

        // Takes first, so a take's richer record beats a bare `gen.landed`.
        for t in &project.takes {
            for hash in t.asset_hashes.values() {
                idx.gen_by_hash
                    .entry(hash.as_str())
                    .or_insert_with(|| GenRecord {
                        source_command: t.source_command.clone(),
                        request_id: t.request_id.clone(),
                        take_id: Some(t.take_id.clone()),
                        engine_identity: t.engine_identity.clone(),
                    });
            }
        }

        let clip_id = |e: &'a Envelope, key: &str| -> Option<&'a str> {
            e.params.get(key).and_then(Value::as_str)
        };

        for e in journal {
            match e.name.as_str() {
                "gen.landed" => {
                    let record = || GenRecord {
                        source_command: e
                            .params
                            .get("sourceCommand")
                            .and_then(Value::as_str)
                            .unwrap_or("gen.song")
                            .to_string(),
                        request_id: e
                            .params
                            .get("requestId")
                            .and_then(Value::as_str)
                            .unwrap_or_default()
                            .to_string(),
                        take_id: e.params.get("takeId").and_then(Value::as_str).map(String::from),
                        engine_identity: e
                            .params
                            .get("engineIdentity")
                            .cloned()
                            .unwrap_or(Value::Null),
                    };
                    for hash in params_asset_hashes(&e.params) {
                        idx.gen_by_hash.entry(hash).or_insert_with(record);
                    }
                }
                "clip.place" => {
                    if e.actor.name == "import" {
                        if let Some(id) = clip_id(e, "clipId") {
                            idx.imported.insert(id);
                        }
                    }
                }
                "clip.placeMidi" | "note.add" => {
                    if let Some(id) = clip_id(e, "clipId") {
                        let w = idx.note_writers.entry(id).or_default();
                        if e.actor.name == RECORD_ACTOR {
                            w.recorded = true;
                        } else {
                            w.authored = true;
                        }
                    }
                }
                "clip.split" | "clip.duplicate" => {
                    if let (Some(new), Some(parent)) =
                        (clip_id(e, "newClipId"), clip_id(e, "clipId"))
                    {
                        idx.derived_from.entry(new).or_insert(parent);
                    }
                }
                name => {
                    if name.starts_with("gen.") {
                        if let Some(rid) = e.params.get("requestId").and_then(Value::as_str) {
                            idx.gen_request.entry(rid).or_insert(e);
                        }
                    } else if name.starts_with("record.") {
                        for key in ["clipId", "newClipId"] {
                            if let Some(id) = clip_id(e, key) {
                                idx.recorded_place.insert(id);
                            }
                        }
                    }
                }
            }
        }
        idx
    }

    /// Who wrote this note clip's notes, following split/duplicate back to the
    /// material the clip is made of. Depth-bounded: the map is built from
    /// `or_insert` on distinct new ids so it cannot cycle, but a corrupt journal
    /// must not hang an export.
    fn note_writers_for(&self, clip_id: &str) -> NoteWriters {
        let mut out = NoteWriters::default();
        let mut id = clip_id;
        for _ in 0..64 {
            if let Some(w) = self.note_writers.get(id) {
                out.recorded |= w.recorded;
                out.authored |= w.authored;
            }
            match self.derived_from.get(id) {
                Some(parent) if *parent != id => id = parent,
                _ => break,
            }
        }
        out
    }
}

/// Classify one clip and build its `lineage` object.
fn classify_clip(clip: &Clip, index: &OriginIndex) -> (ClipOrigin, Value) {
    let hash = clip.source_id.as_str();

    // A note clip has NO asset, so its hash is the empty string. Looking that up
    // can only ever produce a false match against a generative record carrying
    // an empty asset hash — never a true one.
    if !hash.is_empty() {
        if let Some(gen) = index.gen_by_hash.get(hash) {
            // A gen record exists; read the originating gen.* request for the
            // prompt and the declared source (imported songs stay imported
            // after separation).
            let request = index.gen_request.get(gen.request_id.as_str()).copied();
            let declared_source = request
                .and_then(|e| e.params.get("source"))
                .and_then(Value::as_str)
                .unwrap_or("generated");
            let prompt = request.and_then(gen_request_prompt);

            let mut lineage = Map::new();
            lineage.insert("sourceCommand".into(), json!(gen.source_command));
            lineage.insert("requestId".into(), json!(gen.request_id));
            if let Some(t) = &gen.take_id {
                lineage.insert("takeId".into(), json!(t));
            }
            if let Some(p) = prompt {
                lineage.insert("prompt".into(), json!(p));
            }
            lineage.insert("engine".into(), normalize_engine_identity(&gen.engine_identity));

            // An explicitly-imported (then separated) source is not AI-born.
            let origin = if gen.source_command.starts_with("record.") {
                ClipOrigin::Recorded
            } else if declared_source.eq_ignore_ascii_case("imported") {
                lineage.insert("declaredSource".into(), json!("imported"));
                ClipOrigin::Imported
            } else {
                ClipOrigin::Generated
            };
            return (origin, Value::Object(lineage));
        }
    }

    // A journaled `record.*` command placing the clip. Unreachable today (every
    // `record.*` in the catalog is `journaled: false`), kept so the branch stays
    // right if one ever becomes journaled.
    if index.recorded_place.contains(clip.id.as_str()) {
        return (
            ClipOrigin::Recorded,
            json!({ "sourceCommand": "record", "note": "captured from an audio input" }),
        );
    }

    // A NOTE clip. There is no asset and no capture, so neither "imported" nor
    // "generated" can be true of it. The journal says which of the two human
    // origins it is: the MIDI record path stamps every command it submits with
    // the `record` actor (`host.rs` `host_record_stop`), the piano roll and the
    // Instrument button do not. `actor` is one of the seven hashed envelope
    // fields, so this reads a fact that was already in the chain — no new
    // command, no new param, nothing added to the journal.
    if clip.is_midi() {
        let w = index.note_writers_for(&clip.id);
        return if w.recorded {
            let note = if w.authored {
                "played on a MIDI input; some notes in this clip were also written in the piano roll"
            } else {
                "played on a MIDI input"
            };
            (
                ClipOrigin::Recorded,
                // The journal has no command NAMED record.midi; this is the txn
                // reason the record path opens its transaction with, which is
                // the entry that ties the take together.
                json!({ "sourceCommand": "record.midi", "note": note }),
            )
        } else {
            (
                ClipOrigin::Authored,
                json!({ "sourceCommand": "clip.placeMidi", "note": "notes written in the piano roll" }),
            )
        };
    }

    let source_command = if index.imported.contains(clip.id.as_str()) {
        "import.audio"
    } else {
        "clip.place"
    };
    (ClipOrigin::Imported, json!({ "sourceCommand": source_command }))
}

/// Iterate the asset-hash values of a `gen.landed` params object.
fn params_asset_hashes(params: &Value) -> impl Iterator<Item = &str> {
    params
        .get("assetHashes")
        .and_then(Value::as_object)
        .into_iter()
        .flat_map(|m| m.values())
        .filter_map(Value::as_str)
}

/// Pull the human prompt from a gen.* request (caption for songs, instruction
/// for revise/layer).
fn gen_request_prompt(e: &Envelope) -> Option<String> {
    let p = &e.params;
    p.get("request")
        .and_then(|r| r.get("caption"))
        .and_then(Value::as_str)
        .or_else(|| p.get("instruction").and_then(Value::as_str))
        .or_else(|| p.get("request").and_then(|r| r.get("instruction")).and_then(Value::as_str))
        .or_else(|| p.get("caption").and_then(Value::as_str))
        .map(str::to_string)
}

/// Normalize an engineIdentity value into the manifest's `engine` object,
/// keeping only known fields (model/steps/seed/device) with honest omission.
fn normalize_engine_identity(id: &Value) -> Value {
    let mut e = Map::new();
    if let Some(m) = id.get("model").and_then(Value::as_str) {
        e.insert("model".into(), json!(m));
    }
    if let Some(s) = id.get("steps").and_then(Value::as_i64) {
        e.insert("steps".into(), json!(s));
    }
    if let Some(s) = id.get("seed").and_then(Value::as_i64) {
        e.insert("seed".into(), json!(s));
    }
    if let Some(d) = id.get("device").and_then(Value::as_str) {
        e.insert("device".into(), json!(d));
    }
    Value::Object(e)
}

/// The project's content end in ticks (max clip end across tracks).
fn project_end_ticks(project: &Project) -> u64 {
    project
        .tracks
        .iter()
        .flat_map(|t| t.clips.iter())
        .map(|c| c.start_ticks.saturating_add(c.length_ticks))
        .max()
        .unwrap_or(0)
}

fn round2(x: f64) -> f64 {
    (x * 100.0).round() / 100.0
}

fn round4(x: f64) -> f64 {
    (x * 10_000.0).round() / 10_000.0
}
